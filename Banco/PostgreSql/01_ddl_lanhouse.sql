BEGIN;
CREATE TABLE maquinas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL,
    grupo VARCHAR(60),
    endereco_ip INET,
    sistema_operacional VARCHAR(100),
    processador VARCHAR(150),
    memoria_gb NUMERIC(6,2),
    armazenamento_gb NUMERIC(8,2),
    status VARCHAR(20) NOT NULL DEFAULT 'offline'
        CHECK (status IN ('online', 'offline', 'manutencao')),
    observacoes TEXT,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizada_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CHECK (memoria_gb IS NULL OR memoria_gb > 0),
    CHECK (armazenamento_gb IS NULL OR armazenamento_gb > 0)
);

CREATE TABLE softwares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    versao VARCHAR(50),
    categoria VARCHAR(60),
    fabricante VARCHAR(100),
    UNIQUE (nome, versao)
);

CREATE TABLE maquina_software (
    maquina_id BIGINT NOT NULL
        REFERENCES maquinas(id) ON DELETE CASCADE,
    software_id BIGINT NOT NULL
        REFERENCES softwares(id) ON DELETE RESTRICT,
    instalado_em DATE,
    observacoes TEXT,
    PRIMARY KEY (maquina_id, software_id)
);

CREATE TABLE sessoes_uso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maquina_id BIGINT NOT NULL
        REFERENCES maquinas(id) ON DELETE RESTRICT,
    inicio TIMESTAMPTZ NOT NULL,
    fim TIMESTAMPTZ,
    CHECK (fim IS NULL OR fim >= inicio)
);

CREATE INDEX idx_sessoes_maquina_inicio
    ON sessoes_uso (maquina_id, inicio DESC);

CREATE UNIQUE INDEX uq_sessao_maquina_aberta
    ON sessoes_uso (maquina_id)
    WHERE fim IS NULL;

CREATE TABLE incidentes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maquina_id BIGINT NOT NULL
        REFERENCES maquinas(id) ON DELETE RESTRICT,
    titulo VARCHAR(150) NOT NULL,
    descricao TEXT,
    severidade VARCHAR(15) NOT NULL DEFAULT 'media'
        CHECK (severidade IN ('baixa', 'media', 'alta', 'critica')),
    status VARCHAR(20) NOT NULL DEFAULT 'aberto'
        CHECK (status IN ('aberto', 'em_atendimento', 'resolvido', 'cancelado')),
    aberto_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolvido_em TIMESTAMPTZ,
    CHECK (resolvido_em IS NULL OR resolvido_em >= aberto_em)
);

CREATE INDEX idx_incidentes_status
    ON incidentes (status, aberto_em DESC);

CREATE INDEX idx_incidentes_maquina
    ON incidentes (maquina_id, aberto_em DESC);

CREATE TABLE manutencoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maquina_id BIGINT NOT NULL
        REFERENCES maquinas(id) ON DELETE RESTRICT,
    incidente_id BIGINT
        REFERENCES incidentes(id) ON DELETE SET NULL,
    descricao TEXT NOT NULL,
    tipo VARCHAR(20) NOT NULL
        CHECK (tipo IN ('preventiva', 'corretiva')),
    custo NUMERIC(10,2) NOT NULL DEFAULT 0
        CHECK (custo >= 0),
    inicio TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fim TIMESTAMPTZ,
    responsavel_tecnico VARCHAR(120),
    CHECK (fim IS NULL OR fim >= inicio)
);

CREATE INDEX idx_manutencoes_maquina
    ON manutencoes (maquina_id, inicio DESC);

CREATE TABLE contratos_internet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provedor VARCHAR(120) NOT NULL,
    identificacao VARCHAR(120),
    velocidade_mbps INTEGER,
    valor_mensal NUMERIC(10,2),
    inicio_vigencia DATE,
    fim_vigencia DATE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CHECK (velocidade_mbps IS NULL OR velocidade_mbps > 0),
    CHECK (valor_mensal IS NULL OR valor_mensal >= 0),
    CHECK (
        fim_vigencia IS NULL
        OR inicio_vigencia IS NULL
        OR fim_vigencia >= inicio_vigencia
    )
);

COMMIT;
